                        lux = 115000f, temperatureK = 5500f, filter = Color.white,
                        elevationDeg = 20f, azimuthDeg = 248f, angularDiameter = 0.54f,   // review 3: at 27 degrees and 5750 K the '5:42 PM golden afternoon' was white mid-afternoon light
                        volumetricDimmer = 1.0f, shadowDimmer = 1f,
                        wetness = 0.08f, rain = 0f, lightningRateScale = 0f, lightningLux = 0f
                    };
                case AtmospherePreset.DuskTransition:
                    return new KeyLook
                    {
                        lux = 115000f, temperatureK = 5750f, filter = Color.white,
                        elevationDeg = 5.5f, azimuthDeg = 262f, angularDiameter = 0.54f,
                        volumetricDimmer = 1.2f, shadowDimmer = 1f,
                        wetness = 0.35f, rain = 0.25f, lightningRateScale = 0.35f, lightningLux = 2600f
                    };
                case AtmospherePreset.NightCalm:
                    return new KeyLook
                    {
                        // The moon sits low ahead of the player's eastward route (the route runs +X = azimuth 90): the
                        // wet ground glints back at the camera and everything alive is a silhouette against the haze.
