        /// <summary>
        /// Player brightness preference in EV stops (Settings screen), applied on top of every preset as post
        /// exposure through its own global Volume. 0 = as authored; clamp -1.5..+1.5.
        /// </summary>
        public static float UserBrightnessEV
        {
            get => s_UserBrightnessEV;
            set
            {
                s_UserBrightnessEV = Mathf.Clamp(value, -1.5f, 1.5f);
                if (Instance != null) Instance.ApplyUserBrightness();
            }
        }
        private static float s_UserBrightnessEV;
        private Volume _brightnessVolume;
        private ColorAdjustments _brightnessAdjust;

        private void ApplyUserBrightness()
        {
            if (_brightnessVolume == null)
            {
                if (Mathf.Abs(s_UserBrightnessEV) <= 0.001f) return;   // nothing to apply: do not create the volume
                // A profile ASSET instantiated through Volume.profile (a profile built from scratch at runtime threw
                // a NullReferenceException inside HDRP's volume update on its first frame).
                VolumeProfile asset = Resources.Load<VolumeProfile>("Atmosphere/Look_UserBrightness");
                if (asset == null) return;
                var go = new GameObject("LookVolume_UserBrightness");
                go.transform.SetParent(transform, false);
                _brightnessVolume = go.AddComponent<Volume>();
                _brightnessVolume.enabled = false;
                _brightnessVolume.isGlobal = true;
                _brightnessVolume.priority = 60f;
                _brightnessVolume.sharedProfile = asset;
                if (!_brightnessVolume.profile.TryGet(out _brightnessAdjust)) return;
                _brightnessAdjust.postExposure.overrideState = true;
            }
            if (_brightnessAdjust == null) return;
            _brightnessAdjust.postExposure.value = s_UserBrightnessEV;
            _brightnessVolume.enabled = Mathf.Abs(s_UserBrightnessEV) > 0.001f;
        }

        public static AtmosphereController EnsureInstance()
        {
            if (Instance != null) return Instance;
            var existing = FindAnyObjectByType<AtmosphereController>();
            if (existing != null)
            {
                Instance = existing;
                return Instance;
            }

            var go = new GameObject("[AtmosphereController]");
            Instance = go.AddComponent<AtmosphereController>();
            return Instance;
        }

        private void Awake()
        {
            if (Instance != null && Instance != this)
            {
                Destroy(gameObject);
                return;
            }
            Instance = this;
            CacheLights();
            BuildLookVolumes();
            BuildIndoorVolume();
            WorldRegistry.EnsureInstance().RegisterAtmosphereController(this);
            _currentPreset = startPreset;
            _liveKey = GetKeyLook(_currentPreset);
            ApplyWeightsImmediate(_currentPreset);
            ApplyKeyLook(_liveKey, 1f);
            ApplyUserBrightness();
        }

        private void OnEnable()
        {
            GameEvents.OnAtmosphereChanged += OnAtmosphereEvent;
            GameEvents.OnLightningFlash += OnLightningEvent;
        }

        private void OnDisable()
        {
            GameEvents.OnAtmosphereChanged -= OnAtmosphereEvent;
            GameEvents.OnLightningFlash -= OnLightningEvent;
            EndLightningShadows();
            Shader.SetGlobalFloat(AtmoDrivenId, 0f);
            Shader.SetGlobalFloat(IndoorWeightId, 0f);
        }

        private static Vector3[] BuildEnclosureRays()
        {
            // 4 rays at 45 degrees up and 4 at 20 degrees up (turned 45 degrees), plus straight up (index 0)
            var rays = new Vector3[9];
            rays[0] = Vector3.up;
            for (int i = 0; i < 4; i++)
            {
                float a = i * 90f * Mathf.Deg2Rad;
                rays[1 + i] = new Vector3(Mathf.Sin(a), 1f, Mathf.Cos(a)).normalized;
                float b = (i * 90f + 45f) * Mathf.Deg2Rad;
                rays[5 + i] = new Vector3(Mathf.Sin(b), Mathf.Tan(20f * Mathf.Deg2Rad), Mathf.Cos(b)).normalized;
            }
            return rays;
        }

        private void BuildIndoorVolume()
        {
            VolumeProfile profile = Resources.Load<VolumeProfile>("Atmosphere/Look_Indoor");
            if (profile == null) return;
            var go = new GameObject("LookVolume_Indoor");
            go.transform.SetParent(transform, false);
            _indoorVolume = go.AddComponent<Volume>();
            _indoorVolume.isGlobal = true;
            _indoorVolume.priority = 30f;          // above the five looks, below the brightness setting
            _indoorVolume.weight = 0f;
            _indoorVolume.sharedProfile = profile;
            _indoorVolume.enabled = false;
            // a private copy: its sky-ambient value follows day and night (see UpdateIndoor)
            if (!_indoorVolume.profile.TryGet(out _indoorIlc)) _indoorIlc = null;
            if (!_indoorVolume.profile.TryGet(out _indoorExposure)) _indoorExposure = null;
            if (!_indoorVolume.profile.TryGet(out _indoorWb)) _indoorWb = null;
        }

        /// <summary>Weight of one preset's look volume right now (0..1).</summary>
        private float LookWeight(AtmospherePreset preset)
        {
            int i = Array.IndexOf(AllPresets, preset);
            if (i < 0 || _lookVolumes[i] == null || !_lookVolumes[i].enabled) return 0f;
            return Mathf.Clamp01(_lookVolumes[i].weight);
        }

        /// <summary>The lower exposure limit of the look(s) currently shown, before the indoor volume.</summary>
        private float BlendedLookEvMin()
        {
            if (!_lookEvMinRead)
            {
                for (int i = 0; i < _lookVolumes.Length; i++)
                {
                    _lookEvMin[i] = IndoorNightEvMin;
                    Volume v = _lookVolumes[i];
                    if (v != null && v.sharedProfile != null && v.sharedProfile.TryGet(out Exposure ex)) _lookEvMin[i] = ex.limitMin.value;
                }
                _lookEvMinRead = true;
            }
            float sum = 0f, weight = 0f;
            for (int i = 0; i < _lookVolumes.Length; i++)
            {
                Volume v = _lookVolumes[i];
                if (v == null || !v.enabled || v.weight <= 0f) continue;
                sum += _lookEvMin[i] * v.weight;
                weight += v.weight;
            }
            return weight > 0.001f ? sum / weight : IndoorNightEvMin;
        }

        /// <summary>How enclosed the camera is: a ceiling straight up and walls or ceiling on most slanted rays.</summary>
        // ---- Blackout base ------------------------------------------------------------------------------------------
        // Review 3: with the flashlight off, blackout walls away from the battery pools sat at 10-14/255, under the
        // 15-30 the criteria ask for. A dark-adapted eye sees a room; a camera at a fixed floor does not. Enclosed
        // blackout rooms get a dim, cool, shadowless base from four sides and from below: no pools, no falloff, nothing
        // that moves with the player. It only runs while the camera is indoors, so the night outside keeps its blacks.
        public static float BlackoutBaseLux = 1.0f;     // measured: darkest tenth of a blackout room 10-11 -> 12-14/255, pixels under 16/255 33 % -> 23 %
        private Light[] _baseFill;
        private static readonly Vector3[] BaseFillTravel =
        {
            new Vector3(0.87f, -0.5f, 0f), new Vector3(-0.87f, -0.5f, 0f), new Vector3(0f, -0.5f, 0.87f), new Vector3(0f, -0.5f, -0.87f),
            new Vector3(0f, 1f, 0f)
        };

        private void UpdateBlackoutBase(float k)
        {
            if (_baseFill == null)
            {
                if (k < 0.01f) return;
                _baseFill = new Light[BaseFillTravel.Length];
                for (int i = 0; i < _baseFill.Length; i++)
                {
                    var go = new GameObject("BlackoutBase_" + i) { hideFlags = HideFlags.DontSave };
                    go.transform.SetParent(transform, false);
                    go.transform.rotation = Quaternion.LookRotation(BaseFillTravel[i].normalized, Mathf.Abs(BaseFillTravel[i].y) > 0.9f ? Vector3.forward : Vector3.up);
                    Light l = go.AddComponent<Light>();
                    HDAdditionalLightData hd = go.AddComponent<HDAdditionalLightData>();
                    l.type = LightType.Directional;
                    l.lightUnit = LightUnit.Lux;
                    l.shadows = LightShadows.None;
                    l.useColorTemperature = false;
                    l.color = new Color(0.80f, 0.88f, 1.0f);
                    l.intensity = 0f;
                    hd.interactsWithSky = false;        // not a sun: no disc, no sky lighting
                    hd.affectsVolumetric = false;
                    hd.affectSpecular = false;
                    l.enabled = false;
                    _baseFill[i] = l;
                }
            }
            for (int i = 0; i < _baseFill.Length; i++)
            {
                if (_baseFill[i] == null) continue;
                float lux = BlackoutBaseLux * k * (i == 4 ? 0.6f : 1f);   // the ceiling gets a little less than the walls
                _baseFill[i].intensity = lux;
                bool on = lux > 0.004f;
                if (_baseFill[i].enabled != on) _baseFill[i].enabled = on;
            }
        }

        private void UpdateIndoor()
        {
            if (_indoorVolume == null) return;
            _indoorProbeTimer -= Time.unscaledDeltaTime;
            if (_indoorProbeTimer <= 0f)
            {
                _indoorProbeTimer = 0.12f;
                if (_viewer == null || !_viewer.gameObject.activeInHierarchy)
                {
                    Camera cam = Camera.main;
                    _viewer = cam != null ? cam.transform : null;
                }
                float enclosure = 0f;
                if (_viewer != null)
                {
                    int mask = GameLayers.EnvironmentAndDoorMask | GameLayers.Mask(GameLayers.RainBlocker);
                    Vector3 origin = _viewer.position;
                    if (Physics.Raycast(origin, EnclosureRays[0], 14f, mask, QueryTriggerInteraction.Ignore))
                    {
                        int hits = 0;
                        for (int i = 1; i < EnclosureRays.Length; i++)
                        {
                            float reach = i < 5 ? 14f : 22f;
                            if (Physics.Raycast(origin, EnclosureRays[i], reach, mask, QueryTriggerInteraction.Ignore)) hits++;
                        }
                        enclosure = hits / 8f;
                    }
                }
                // an open canopy scores about 0.5, a room with an open door 0.875, a closed room 1
                _indoorTarget = Mathf.SmoothStep(0f, 1f, Mathf.InverseLerp(0.58f, 0.9f, enclosure));
            }

            // 0 under the moon (tens of lux), 1 under the sun (tens of thousands)
            float daylight = Mathf.InverseLerp(2.5f, 4.5f, Mathf.Log10(Mathf.Max(1f, _liveKey.lux)));
            Shader.SetGlobalFloat(AtmoDaylightId, daylight);
            float storm = _looksReady ? LookWeight(AtmospherePreset.NightStormBlackout) : 0f;
            if (_indoorIlc != null)
            {
                float night = Mathf.Lerp(IndoorDiffuseNight, IndoorDiffuseBlackout, storm);
                _indoorIlc.indirectDiffuseLightingMultiplier.value = Mathf.Lerp(night, IndoorDiffuseDay, daylight);
            }
            if (_indoorWb != null) _indoorWb.temperature.value = IndoorBlackoutTemperature * storm;
            if (_indoorExposure != null && _looksReady)
            {
                // never below the look's own floor (day and dusk are far above it anyway)
                _indoorExposure.limitMin.value = Mathf.Max(BlendedLookEvMin(), IndoorNightEvMin);
            }
            _indoorWeight = Mathf.MoveTowards(_indoorWeight, _indoorTarget, Time.unscaledDeltaTime * 1.6f);
            UpdateBlackoutBase(_indoorWeight * storm * (1f - daylight));
            _indoorVolume.weight = _indoorWeight;
            _indoorVolume.enabled = _indoorWeight > 0.002f;
            Shader.SetGlobalFloat(IndoorWeightId, _indoorWeight);
        }

        private static readonly int AtmosphereBlendingId = Shader.PropertyToID("_CretaceaAtmosphereBlending");

        // The looks refresh the sky's ambient light and reflection twice a second: fine for a standing sky, but during
        // a sunset the exposure range moved to the night's within a second while the ground was still lit by an
        // ambient probe half a second old (daylight): a one-second flash on the plaza at nightfall. While a blend
        // runs (and for a moment after) this volume makes the sky refresh every frame.
        private Volume _blendSkyVolume;
        private float _blendSkyUntil;

        private void UpdateBlendSkyVolume()
        {
            if (_blendRoutine != null) _blendSkyUntil = Time.unscaledTime + 1.0f;
            bool on = Time.unscaledTime < _blendSkyUntil;
            if (on && _blendSkyVolume == null)
            {
                var go = new GameObject("LookVolume_BlendSky");
                go.transform.SetParent(transform, false);
                _blendSkyVolume = go.AddComponent<Volume>();
                _blendSkyVolume.isGlobal = true;
                _blendSkyVolume.priority = 45f;
                var profile = ScriptableObject.CreateInstance<VolumeProfile>();
                profile.name = "Look_BlendSky (runtime)";
                profile.hideFlags = HideFlags.DontSave;
                var sky = profile.Add<PhysicallyBasedSky>(false);
                sky.updateMode.overrideState = true;
                sky.updateMode.value = EnvironmentUpdateMode.Realtime;
                sky.updatePeriod.overrideState = true;
                sky.updatePeriod.value = 0f;
                _blendSkyVolume.sharedProfile = profile;
            }
            if (_blendSkyVolume != null && _blendSkyVolume.enabled != on) _blendSkyVolume.enabled = on;
        }
        private static readonly int AtmoDaylightId = Shader.PropertyToID("_AtmoDaylight");   // 0 under the moon, 1 under the sun

        private void Update()
        {
            UpdateIndoor();
            Shader.SetGlobalFloat(AtmosphereBlendingId, _blendRoutine != null ? 1f : 0f);
            UpdateBlendSkyVolume();

            float rate = lightningRate * _liveKey.lightningRateScale;
            if (!lightningEnabled || rate <= 0.001f) return;
            if (GameState.Instance != null && GameState.Instance.IsPaused) return;

            _nextLightningTimer -= Time.deltaTime;
            if (_nextLightningTimer <= 0f)
            {
                _nextLightningTimer = UnityEngine.Random.Range(6.5f, 16.0f) / Mathf.Max(0.25f, rate);
                TriggerLightningFlash(UnityEngine.Random.Range(0.55f, 1.0f), withThunder: true);
            }
        }

        /// <summary>
        /// Edit-mode preview for editor tools (Awake has not run): shows one preset through the scene's own global
        /// Volume and key light, so the Scene view and edit-mode captures match what Play mode will show.
        /// </summary>
        public void PreviewInEditor(AtmospherePreset preset)
        {
            CacheLights();
            VolumeProfile profile = Resources.Load<VolumeProfile>("Atmosphere/Look_" + preset);
            if (globalAtmosphereVolume != null && profile != null)
            {
                globalAtmosphereVolume.sharedProfile = profile;
                globalAtmosphereVolume.isGlobal = true;
                globalAtmosphereVolume.priority = 20f;
                globalAtmosphereVolume.weight = 1f;
                globalAtmosphereVolume.enabled = true;
            }
            startPreset = preset;
            _currentPreset = preset;
            _liveKey = GetKeyLook(preset);
            ApplyKeyLook(_liveKey, 1f);
        }

        // ------------------------------------------------------------------------------------------------------------
        private void CacheLights()
        {
            if (keyDirectionalLight != null)
            {
                keyDirectionalLight.lightUnit = LightUnit.Lux;
                _keyHdLight = keyDirectionalLight.GetComponent<HDAdditionalLightData>();
                if (_keyHdLight != null)
                {
                    _keyHdLight.interactsWithSky = true;
                    _keyHdLight.affectsVolumetric = true;
                }
            }

            if (lightningFlashLight != null)
            {
                lightningFlashLight.lightUnit = LightUnit.Lux;
                _lightningHdLight = lightningFlashLight.GetComponent<HDAdditionalLightData>();
                if (_lightningHdLight != null)
                {
                    _lightningHdLight.interactsWithSky = false;
                    _lightningHdLight.affectsVolumetric = true;
                }
                lightningFlashLight.enabled = false;
            }
        }

        private void BuildLookVolumes()
        {
            int found = 0;
            for (int i = 0; i < AllPresets.Length; i++)
            {
                VolumeProfile profile = Resources.Load<VolumeProfile>("Atmosphere/Look_" + AllPresets[i]);
                if (profile == null) continue;
                found++;

                var go = new GameObject("LookVolume_" + AllPresets[i]);
                go.transform.SetParent(transform, false);
                Volume v = go.AddComponent<Volume>();
                v.isGlobal = true;
                v.priority = 20f + i * 0.01f;
                v.weight = 0f;
                v.sharedProfile = profile;
                _lookVolumes[i] = v;
            }

            _looksReady = found == AllPresets.Length;
            if (_looksReady)
            {
                // The generated scene still carries the old single profile; the five look volumes replace it.
                if (globalAtmosphereVolume != null) globalAtmosphereVolume.enabled = false;
            }
            else
            {
                Debug.LogWarning("[Atmosphere] Look profiles missing in Resources/Atmosphere (found " + found + "/5). Run the Look Pass.");
            }
        }

        private static int IndexOf(AtmospherePreset preset)
        {
            for (int i = 0; i < AllPresets.Length; i++) if (AllPresets[i] == preset) return i;
            return 0;
        }

        private void ApplyWeightsImmediate(AtmospherePreset preset)
        {
            int target = IndexOf(preset);
            for (int i = 0; i < _lookVolumes.Length; i++)
            {
                if (_lookVolumes[i] == null) continue;
                _lookVolumes[i].weight = i == target ? 1f : 0f;
                _lookVolumes[i].enabled = i == target;
            }
        }

        private void OnAtmosphereEvent(AtmospherePreset preset, float blendSeconds)
        {
            SetPreset(preset, blendSeconds);
        }

        private void OnLightningEvent(float intensity01, bool withThunder)
        {
            TriggerLightningFlash(intensity01, withThunder);
        }

        public void SetPreset(AtmospherePreset preset, float blendSeconds = 0f)
        {
            AtmospherePreset from = _currentPreset;
            _currentPreset = preset;

            if (_blendRoutine != null)
            {
                StopCoroutine(_blendRoutine);
                _blendRoutine = null;
            }

            if (blendSeconds <= 0.001f || from == preset)
            {
                _liveKey = GetKeyLook(preset);
                ApplyWeightsImmediate(preset);
                ApplyKeyLook(_liveKey, 1f);
                BumpAtmosphereEpoch();
                if (isActiveAndEnabled) StartCoroutine(BumpAtmosphereEpochLater(2.5f));
                return;
            }

            _blendRoutine = StartCoroutine(BlendRoutine(preset, blendSeconds));
        }

        // ---- reflection probes follow the sky -------------------------------------------------------------------------
        // Outdoor reflection probes (Cretacea.Rendering.ReflectionProbeRefresh) re-render when this global changes. A
        // probe captured in daylight and left alone showed as a bright rectangle on the wet plaza all night.
        private static readonly int AtmosphereEpochId = Shader.PropertyToID("_CretaceaAtmosphereEpoch");
        private float _atmosphereEpoch;

        private void BumpAtmosphereEpoch()
        {
            _atmosphereEpoch += 1f;
            Shader.SetGlobalFloat(AtmosphereEpochId, _atmosphereEpoch);
        }

        private static readonly int AtmosphereSettledId = Shader.PropertyToID("_CretaceaAtmosphereSettled");

        private void BumpAtmosphereSettled()
        {
            BumpAtmosphereEpoch();
            Shader.SetGlobalFloat(AtmosphereSettledId, _atmosphereEpoch);   // indoor probes (windows, skylights)
        }

        private IEnumerator BumpAtmosphereEpochLater(float seconds)
        {
            yield return new WaitForSeconds(seconds);      // auto exposure has settled by then
            BumpAtmosphereSettled();
        }

        public void SetLobbySkylightRain(bool emitting)
        {
            if (lobbyBrokenSkylightRainSystems == null) return;
            for (int i = 0; i < lobbyBrokenSkylightRainSystems.Length; i++)
            {
                ParticleSystem ps = lobbyBrokenSkylightRainSystems[i];
                if (ps == null) continue;
                var emission = ps.emission;
                emission.enabled = emitting;
                if (emitting && !ps.isPlaying) ps.Play();
                else if (!emitting && ps.isPlaying) ps.Stop();
            }
        }

        private Vector3? _forcedStrikeDirection;

        /// <summary>
        /// A strike whose light travels in a given direction (for staged beats: lit from behind, a creature is a
        /// black silhouette against glowing haze instead of one more lit object in a lit landscape).
        /// </summary>
        public void TriggerLightningFlashFrom(Vector3 lightTravelDirection, float intensity01, bool withThunder = true)
        {
            if (lightTravelDirection.sqrMagnitude > 0.0001f) _forcedStrikeDirection = lightTravelDirection.normalized;
            TriggerLightningFlash(intensity01, withThunder);
        }

        private bool _lightningHeld;

        /// <summary>Captures and tests: hold a strike at a fixed level from a fixed direction (0 releases it).</summary>
        public void HoldLightningForCapture(float level01, float azimuthDeg = 200f, float elevationDeg = 55f)
        {
            if (_lightningRoutine != null) { StopCoroutine(_lightningRoutine); _lightningRoutine = null; }
            float peakLux = Mathf.Max(0f, _liveKey.lightningLux);
            _lightningHeld = level01 > 0.001f;
            if (!_lightningHeld)
            {
                SetLightningLevel(0f, peakLux);
                if (lightningFlashLight != null) lightningFlashLight.enabled = false;
                EndLightningShadows();
                return;
            }
            if (lightningFlashLight != null && peakLux > 0.01f)
            {
                lightningFlashLight.transform.rotation = Quaternion.Euler(elevationDeg, azimuthDeg, 0f);
                lightningFlashLight.color = new Color(0.88f, 0.92f, 1.0f);   // a little less blue: the wet grass went teal-mint under a strike (review 3)
                lightningFlashLight.enabled = true;
                if (_lightningHdLight != null) _lightningHdLight.SetLightDimmer(1f, 0.55f);
                BeginLightningShadows();
            }
            SetLightningLevel(Mathf.Clamp01(level01), peakLux);
        }

        public void TriggerLightningFlash(float intensity01, bool withThunder = true)
        {
            if (_lightningHeld) return;
            if (_lightningRoutine != null)
            {
                StopCoroutine(_lightningRoutine);
                EndLightningShadows();
            }
            _lightningRoutine = StartCoroutine(LightningFlashRoutine(Mathf.Clamp01(intensity01), withThunder));
        }

        // HDRP gives cascaded shadows to one directional light. For the fraction of a second a strike lasts, the
        // strike takes them from the moon: hard shadows leap across the yard, and roofs keep the flash out of rooms.
        private bool _lightningOwnsShadows;
        private LightShadows _keyShadowsBefore = LightShadows.Soft;

        private void BeginLightningShadows()
        {
            if (lightningFlashLight == null || _lightningOwnsShadows) return;
            if (keyDirectionalLight != null)
            {
                _keyShadowsBefore = keyDirectionalLight.shadows;
                keyDirectionalLight.shadows = LightShadows.None;
            }
            lightningFlashLight.shadows = LightShadows.Soft;
            _lightningOwnsShadows = true;
        }

        private void EndLightningShadows()
        {
            if (!_lightningOwnsShadows) return;
            if (lightningFlashLight != null) lightningFlashLight.shadows = LightShadows.None;
            if (keyDirectionalLight != null) keyDirectionalLight.shadows = _keyShadowsBefore;
            _lightningOwnsShadows = false;
        }

        // ------------------------------------------------------------------------------------------------------------
        private const float TwilightElevation = -7f;

        private IEnumerator BlendRoutine(AtmospherePreset target, float duration)
        {
            int targetIndex = IndexOf(target);
            for (int i = 0; i < _lookVolumes.Length; i++)
            {
                Volume v = _lookVolumes[i];
                _weightsFrom[i] = v != null && v.enabled ? v.weight : 0f;
                if (v != null && i == targetIndex) v.enabled = true;
            }

            KeyLook fromKey = _liveKey;
            KeyLook toKey = GetKeyLook(target);
            Vector3 fromDir = DirectionFor(fromKey);
            Vector3 toDir = DirectionFor(toKey);
            // Sun <-> moon (or a big jump across the sky): dip the key light to black, swap, come back up.
            bool dip = Vector3.Angle(fromDir, toDir) > 30f || Mathf.Abs(Mathf.Log(fromKey.lux / Mathf.Max(0.0001f, toKey.lux), 2f)) > 6f;

            float elapsed = 0f;
            float sinceProbe = 0f;
            while (elapsed < duration)
            {
                elapsed += Time.deltaTime;
                sinceProbe += Time.deltaTime;
                if (sinceProbe >= 2.5f) { sinceProbe = 0f; BumpAtmosphereEpoch(); }
                float k = Mathf.SmoothStep(0f, 1f, Mathf.Clamp01(elapsed / duration));

                KeyLook live = LerpKey(fromKey, toKey, k);
                float dimmer = 1f;
                float lookK = k;                // how far the grade, exposure range, fog and clouds have crossed over
                if (dip)
                {
                    // Sunset, then moonrise (or moonset, then sunrise): the old key sinks 7 degrees below the horizon
                    // and the new one rises from there. The sky model does the twilight by itself; the light on the
                    // ground fades as the disc crosses the horizon. (A plain fade to black made the dusk shot dip to
                    // black for a second; dimming only the light left the sky at full daylight under a night exposure.)
                    bool firstHalf = k < 0.5f;
                    KeyLook side = firstHalf ? fromKey : toKey;
                    float h = Mathf.SmoothStep(0f, 1f, firstHalf ? k * 2f : (k - 0.5f) * 2f);
                    live.azimuthDeg = side.azimuthDeg;
                    live.lux = side.lux;
                    live.temperatureK = side.temperatureK;
                    live.filter = side.filter;
                    live.angularDiameter = side.angularDiameter;
                    live.elevationDeg = firstHalf ? Mathf.Lerp(side.elevationDeg, TwilightElevation, h)
                                                  : Mathf.Lerp(TwilightElevation, side.elevationDeg, h);
                    // The sun's light on surfaces fades in over three degrees at the horizon (the sky model dims it
                    // further). The moon gets a longer ramp: it rises 38 degrees in two seconds, and under the night
                    // exposure a 0.2 s fade-in read as a flash on the plaza before the camera had adapted.
                    float full = side.lux > 1000f ? 1.5f : 12f;
                    dimmer = Mathf.SmoothStep(0f, 1f, Mathf.InverseLerp(-1.5f, full, live.elevationDeg));
                    // The afterglow fades with the sun's depth: at the handover the sky is as dark as the other key's
                    // sky. (Left at full strength, the twilight above the ridge was a clipped white strip under the
                    // night exposure in the opening's night aerial.)
                    KeyLook other = firstHalf ? toKey : fromKey;
                    // (Fast: the cloud deck stays fully sunlit from below however deep the sun is, so the fade is done
                    // by -4 degrees. Fading down to -7 left 23,000 lux on the clouds at -3 degrees while the exposure
                    // range was already two thirds of the way to the night's: a one-second flash on the plaza.)
                    if (side.lux > other.lux && live.elevationDeg < 0.5f)
                    {
                        float depth = Mathf.SmoothStep(0f, 1f, Mathf.InverseLerp(0.5f, -4f, live.elevationDeg));
                        live.lux = Mathf.Exp(Mathf.Lerp(Mathf.Log(side.lux), Mathf.Log(Mathf.Max(0.01f, other.lux)), depth));
                    }

                    // The look follows the sun, not the clock: the exposure range of the darker preset must be in
                    // place while the sky is dark. With a linear cross-fade a sunrise spent seconds under a daylight
                    // exposure range in the dark (black frames), and a sunset under a night range in daylight (white).
                    float sunUp = Mathf.SmoothStep(0f, 1f, Mathf.InverseLerp(-6f, 2f, live.elevationDeg));
                    bool fromIsSun = fromKey.lux > toKey.lux;
                    if (fromIsSun) lookK = firstHalf ? 1f - sunUp : 1f;       // sunset, then moonrise under the night look
                    else lookK = firstHalf ? 0f : sunUp;                       // moonset under the night look, then sunrise
                }

                for (int i = 0; i < _lookVolumes.Length; i++)
                {
                    Volume v = _lookVolumes[i];
                    if (v == null) continue;
                    v.weight = Mathf.Lerp(_weightsFrom[i], i == targetIndex ? 1f : 0f, lookK);
                }
                // A strike is as bright as the exposure it is seen under: its lux follows the look, not the clock.
                // (Blended by time, the strike scripted at the cut to the opening's night aerial still had half of
                // the dusk's 2600 lux under the night exposure: the plaza flashed white.)
                live.lightningLux = Mathf.Exp(Mathf.Lerp(Mathf.Log(Mathf.Max(1f, fromKey.lightningLux)), Mathf.Log(Mathf.Max(1f, toKey.lightningLux)), lookK));
                _liveKey = live;
                ApplyKeyLook(live, dimmer);
                yield return null;
            }

            _liveKey = toKey;
            ApplyWeightsImmediate(target);
            ApplyKeyLook(toKey, 1f);
            _blendRoutine = null;
            BumpAtmosphereEpoch();
            yield return new WaitForSeconds(2.5f);
            BumpAtmosphereSettled();
        }

        private static KeyLook LerpKey(KeyLook a, KeyLook b, float k)
        {
            return new KeyLook
            {
                lux = Mathf.Exp(Mathf.Lerp(Mathf.Log(Mathf.Max(0.0001f, a.lux)), Mathf.Log(Mathf.Max(0.0001f, b.lux)), k)),
                temperatureK = Mathf.Lerp(a.temperatureK, b.temperatureK, k),
                filter = Color.Lerp(a.filter, b.filter, k),
                elevationDeg = Mathf.Lerp(a.elevationDeg, b.elevationDeg, k),
                azimuthDeg = Mathf.LerpAngle(a.azimuthDeg, b.azimuthDeg, k),
                angularDiameter = Mathf.Lerp(a.angularDiameter, b.angularDiameter, k),
                volumetricDimmer = Mathf.Lerp(a.volumetricDimmer, b.volumetricDimmer, k),
                shadowDimmer = Mathf.Lerp(a.shadowDimmer, b.shadowDimmer, k),
                wetness = Mathf.Lerp(a.wetness, b.wetness, k),
                rain = Mathf.Lerp(a.rain, b.rain, k),
                lightningRateScale = Mathf.Lerp(a.lightningRateScale, b.lightningRateScale, k),
                lightningLux = Mathf.Lerp(a.lightningLux, b.lightningLux, k)
            };
        }

        /// <summary>Direction the light travels (from the sun / moon toward the ground).</summary>
        private static Vector3 DirectionFor(KeyLook key)
        {
            float el = key.elevationDeg * Mathf.Deg2Rad;
            float az = key.azimuthDeg * Mathf.Deg2Rad;
            Vector3 toLight = new Vector3(Mathf.Sin(az) * Mathf.Cos(el), Mathf.Sin(el), Mathf.Cos(az) * Mathf.Cos(el));
            return -toLight;
        }

        /// <summary>
        /// HDRP draws the disc at its real radiance (the sun: about 10^8 nits, 30,000 times white at the day exposure)
        /// and a flare of the same radiance round it. On screen that was a clipped blob four degrees wide with a lemon
        /// rim, bloom over a third of the sky, and stair steps wherever the low-resolution clouds crossed it (review 2,
        /// the ending). The disc is drawn a few stops over white instead, inside a wide soft flare: it still clips to
        /// a clean disc, thin cloud dims it, and the glow rolls off through the tone curve's shoulder.
        /// (The light itself, and so everything it lights, is unchanged.)
        /// </summary>
        private void ApplyDiscLook(KeyLook key)
        {
            bool sun = key.lux > 1000f;
            float low = sun ? Mathf.InverseLerp(20f, 8f, key.elevationDeg) : 0f;
            _keyHdLight.surfaceTint = sun ? new Color(0.030f, 0.029f, 0.027f) : new Color(0.034f, 0.035f, 0.037f);
            _keyHdLight.flareSize = sun ? Mathf.Lerp(5f, 9f, low) : 4.5f;
            _keyHdLight.flareFalloff = sun ? Mathf.Lerp(6f, 5f, low) : 6f;
            _keyHdLight.flareMultiplier = sun ? Mathf.Lerp(0.00006f, 0.00011f, low) : 0.00006f;
            _keyHdLight.flareTint = sun ? Color.Lerp(Color.white, new Color(1.0f, 0.93f, 0.86f), low) : new Color(0.90f, 0.95f, 1.0f);
        }

        private void ApplyKeyLook(KeyLook key, float dimmer)
        {
            if (keyDirectionalLight != null)
            {
                keyDirectionalLight.transform.rotation = Quaternion.LookRotation(DirectionFor(key), Vector3.up);
                // The sky and the clouds take their brightness from this light's intensity and direction; the dimmer
                // only scales what reaches surfaces (it is 0 while the disc is under the horizon).
                keyDirectionalLight.intensity = Mathf.Max(0.0001f, key.lux);
                keyDirectionalLight.useColorTemperature = true;
                keyDirectionalLight.colorTemperature = key.temperatureK;
                keyDirectionalLight.color = key.filter;
                if (_keyHdLight != null)
                {
                    _keyHdLight.angularDiameter = key.angularDiameter;
                    ApplyDiscLook(key);
                    _keyHdLight.SetLightDimmer(dimmer, key.volumetricDimmer * dimmer);
                    _keyHdLight.SetShadowDimmer(key.shadowDimmer, 1f);
                }
            }

            Shader.SetGlobalFloat(GlobalWetnessId, key.wetness);
            Shader.SetGlobalFloat(RainIntensityId, key.rain);
            Shader.SetGlobalFloat(AtmoRainId, key.rain);
            Shader.SetGlobalFloat(AtmoWetnessId, key.wetness);
            Shader.SetGlobalFloat(AtmoDrivenId, 1f);

            if (exteriorRainSystems != null && Application.isPlaying)
            {
                bool activeRain = key.rain > 0.02f;
                for (int i = 0; i < exteriorRainSystems.Length; i++)
                {
                    ParticleSystem ps = exteriorRainSystems[i];
                    if (ps == null) continue;
                    var emission = ps.emission;
                    emission.enabled = activeRain;
                    if (activeRain && !ps.isPlaying) ps.Play();
                    else if (!activeRain && ps.isPlaying) ps.Stop();
                }
            }
        }

        // ------------------------------------------------------------------------------------------------------------
        private IEnumerator LightningFlashRoutine(float intensity, bool withThunder)
        {
            float peakLux = Mathf.Max(0f, _liveKey.lightningLux);
            if (lightningFlashLight != null && peakLux > 0.01f)
            {
                // every strike comes from somewhere else in the sky
                if (_forcedStrikeDirection.HasValue)
                {
                    lightningFlashLight.transform.rotation = Quaternion.LookRotation(_forcedStrikeDirection.Value, Vector3.up);
                    _forcedStrikeDirection = null;
                }
                else
                {
                    float az = UnityEngine.Random.Range(0f, 360f);
                    float el = UnityEngine.Random.Range(38f, 72f);
                    lightningFlashLight.transform.rotation = Quaternion.Euler(el, az, 0f);
                }
                lightningFlashLight.color = new Color(0.88f, 0.92f, 1.0f);   // a little less blue: the wet grass went teal-mint under a strike (review 3)
                lightningFlashLight.enabled = true;
                if (_lightningHdLight != null) _lightningHdLight.SetLightDimmer(1f, 0.55f);
                BeginLightningShadows();
            }

            SetLightningLevel(intensity, peakLux);
            yield return new WaitForSeconds(0.07f);

            // double stroke, then a quick decay
            SetLightningLevel(intensity * 0.2f, peakLux);
            yield return new WaitForSeconds(0.06f);

            SetLightningLevel(intensity * 0.85f, peakLux);
            yield return new WaitForSeconds(0.10f);

            const float fade = 0.32f;
            float elapsed = 0f;
            while (elapsed < fade)
            {
                elapsed += Time.deltaTime;
                float f = 1f - elapsed / fade;
                SetLightningLevel(intensity * f * f * 0.5f, peakLux);
                yield return null;
            }

            SetLightningLevel(0f, peakLux);
            if (lightningFlashLight != null) lightningFlashLight.enabled = false;
            EndLightningShadows();

            if (withThunder)
            {
                float thunderDelay = intensity > 0.78f ? UnityEngine.Random.Range(0.25f, 0.85f) : UnityEngine.Random.Range(1.2f, 2.8f);
                yield return new WaitForSeconds(thunderDelay);
                string thunderId = intensity > 0.78f ? "amb_thunder_close" : "amb_thunder_far";
                GameEvents.RaisePlaySound(thunderId);
                if (intensity > 0.78f)
                {
                    GameEvents.RaiseCameraTrauma(0.18f * intensity, 1.4f);
                    GameEvents.RaiseSoundCaption("[THUNDER CRACKS OVERHEAD]", 2.2f);
                }
            }

            _lightningRoutine = null;
        }

        private void SetLightningLevel(float level, float peakLux)
        {
            _lightningLevel = level;
            Shader.SetGlobalFloat(LightningGlowId, level);
            if (lightningFlashLight != null)
            {
                lightningFlashLight.intensity = peakLux * level;
            }
        }
