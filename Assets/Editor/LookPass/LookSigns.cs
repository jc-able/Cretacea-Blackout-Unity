using System;
using System.Collections.Generic;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEngine;
using UnityEngine.Rendering;
using UnityEngine.Rendering.HighDefinition;

namespace Cretacea.Editor.Look
{
    /// <summary>
    /// Signs with words. The kit's BuildIlluminatedSign asks this class which artwork a sign shows
    /// (Assets/Art/UI/Signs/*.png), how big the face is and whether it is back-lit; the post-build pass
    /// (<see cref="Apply"/>) then moves sign faces out of the wall they were embedded in and removes faces that
    /// look straight into a wall.
    ///
    /// Brightness: printed plates have no emission (they are lit by the room and the flashlight). Back-lit exit
    /// signs glow at <see cref="BacklitNits"/> on their white pixels: about 1-2x the night scene white (EV 4 = 19 nits).
    /// Measured in Play mode with the current night bloom (threshold 0, scatter 0.68): at 60 nits an exit sign in the
    /// blackout is a green halo with no readable words; at 22 nits it is still a clipped box at blackout exposure; at 10 nits (about the blackout scene white) the green field and white pictogram read.
    /// </summary>
    public static class LookSigns
    {
        public const string SignArtFolder = "Assets/Art/UI/Signs";
        public const string SignMaterialFolder = "Assets/Art/Materials/World/Signs";
        public const float BacklitNits = 10f;
        public const string FaceFront = "SignFace_Front";
        public const string FaceBack = "SignFace_Back";
        /// <summary>A free sign closer than this to a wall behind one face hangs on that wall (the face looking into
        /// the wall is removed and the rest moves onto the wall). The E-0 header is authored 0.38 m off its lintel.</summary>
        private const float FreeSignWallGap = 0.5f;

        // text / name keyword -> artwork stem. First match wins; checked against "TEXT NAME" in upper case.
        private static readonly (Regex rx, string stem)[] StemRules =
        {
            (new Regex(@"E-?0|SERVICEEXITE0|SIGN_E0"), "e0_exit_lightbox"),
            (new Regex(@"EXIT|TOCORRIDOR|TOSTAFFEXIT|EGRESS"), "emergency_exit"),
            (new Regex(@"SECURITY"), "security_office"),
            (new Regex(@"CONTROL"), "control_room"),
            (new Regex(@"RECORD|ARCHIVE"), "records"),
            (new Regex(@"FEED|PREP|VET"), "feed_prep"),
            (new Regex(@"STAFF|AUTHORI[SZ]ED|PERSONNEL"), "staff_only"),
            (new Regex(@"RESTROOM|TOILET|WC\b"), "restroom"),
            (new Regex(@"ASSEMBLY"), "fire_assembly"),
            (new Regex(@"HIGH.?VOLTAGE|DANGER"), "high_voltage"),
            (new Regex(@"SUBSTATION"), "substation_3"),
            (new Regex(@"WAREHOUSE"), "warehouse_b"),
            (new Regex(@"SERVICE.?ROAD"), "service_road_3"),
            (new Regex(@"PADDOCK"), "paddock4_gate"),
            (new Regex(@"TALON|DO NOT TAP"), "talon_ridge_warning"),
            (new Regex(@"WELCOME"), "lobby_welcome"),
        };

        /// <summary>Artwork that is printed on a light box (glows). Everything else is a printed plate.</summary>
        private static readonly HashSet<string> BacklitStems = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
        {
            "emergency_exit", "e0_exit", "e0_exit_decal", E0Lightbox,
        };

        /// <summary>The E-0 header (the target of the climax): a light box made for emission, solid white letters on an
        /// escape-green field, opaque (review 1: the alpha-tested spray stencil shredded into hairlines at 20 m).
        /// Generated by Tools/agent/make_e0_lightbox.py.</summary>
        public const string E0Lightbox = "e0_exit_lightbox";
        /// <summary>Nits of the E-0 light box's white letters (the green field emits ~20 % of that). Storm scene white at
        /// EV 3-3.7 is ~10-15 nits; measured in Play mode at 16 nits the whole face bloomed into a white bar at 20 m, at 9 nits the
        /// letters read but the field washed out to mint; at 3.5 nits the field stays green and the letters white.</summary>
        public const float E0LetterNits = 3.5f;

        private static readonly Dictionary<string, Material> s_cache = new Dictionary<string, Material>();

        /// <summary>Artwork stem for a sign: from an explicit text, the object name, or a textured material.</summary>
        public static string ResolveStem(string text, string objectName, Material signMat)
        {
            string texStem = TextureStemOf(signMat);
            if (!string.IsNullOrEmpty(texStem) && ArtExists(texStem)) return texStem;
            string key = ((text ?? "") + " " + (objectName ?? "")).ToUpperInvariant();
            foreach (var (rx, stem) in StemRules)
            {
                if (rx.IsMatch(key) && ArtExists(stem)) return stem;
            }
            return null;
        }

        public static bool IsBacklit(string stem) => !string.IsNullOrEmpty(stem) && BacklitStems.Contains(stem);

        public static bool ArtExists(string stem) => LoadArt(stem) != null;

        public static Texture2D LoadArt(string stem)
        {
            if (string.IsNullOrEmpty(stem)) return null;
            return AssetDatabase.LoadAssetAtPath<Texture2D>($"{SignArtFolder}/{stem}.png");
        }

        private static string TextureStemOf(Material m)
        {
            if (m == null || !m.HasProperty("_BaseColorMap")) return null;
            Texture t = m.GetTexture("_BaseColorMap");
            if (t == null) return null;
            string path = AssetDatabase.GetAssetPath(t);
            if (string.IsNullOrEmpty(path) || !path.StartsWith(SignArtFolder)) return null;
            return System.IO.Path.GetFileNameWithoutExtension(path);
        }

        /// <summary>The largest face with the artwork's aspect ratio that fits the requested sign size (height may
        /// grow by up to 40 % so wide-format plates do not shrink to a sliver).</summary>
        public static Vector2 FitToArt(string stem, Vector2 size)
        {
            Texture2D t = LoadArt(stem);
            if (t == null || t.height == 0) return size;
            float aspect = t.width / (float)t.height;
            float maxW = size.x, maxH = size.y * 1.4f;
            float w = maxW, h = w / aspect;
            if (h > maxH) { h = maxH; w = h * aspect; }
            return new Vector2(w, h);
        }

        /// <summary>HDRP Lit material showing one sign artwork: alpha-clipped (rounded corners), and when back-lit the
        /// artwork is also its own emission map.</summary>
        public static Material SignMaterial(string stem, bool backlit)
        {
            Texture2D tex = LoadArt(stem);
            if (tex == null) return null;
            string name = backlit ? $"MAT_Sign_{stem}_Lit" : $"MAT_Sign_{stem}";
            if (s_cache.TryGetValue(name, out Material cached) && cached != null) return cached;

            EnsureFolder(SignMaterialFolder);
            string path = $"{SignMaterialFolder}/{name}.mat";
            Material m = AssetDatabase.LoadAssetAtPath<Material>(path);
            if (m == null)
            {
                m = new Material(Shader.Find("HDRP/Lit")) { name = name };
                AssetDatabase.CreateAsset(m, path);
            }
            m.SetTexture("_BaseColorMap", tex);
            m.SetColor("_BaseColor", Color.white);
            m.SetFloat("_Metallic", 0f);
            m.SetFloat("_Smoothness", backlit ? 0.55f : 0.32f);
            m.SetFloat("_AlphaCutoffEnable", 1f);
            m.SetFloat("_AlphaCutoff", 0.5f);
            m.SetFloat("_DoubleSidedEnable", 0f);
            if (stem == E0Lightbox)
            {
                ConfigureLightboxImport(tex);
                m.SetColor("_BaseColor", Color.white);
                m.SetFloat("_AlphaCutoffEnable", 0f);
                m.SetFloat("_Smoothness", 0.62f);
                m.SetTexture("_EmissiveColorMap", tex);
                m.SetColor("_EmissiveColorLDR", Color.white);
                m.SetColor("_EmissiveColor", Color.white * E0LetterNits);
                m.SetFloat("_EmissiveIntensity", E0LetterNits);
                m.SetFloat("_UseEmissiveIntensity", 0f);
                m.SetFloat("_EmissiveExposureWeight", 1f);
            }
            else if (backlit && stem.StartsWith("e0_exit"))
            {
                // E-0 is the escape route: green (Look Bible 3). The stencil art is amber paint; with the alpha clip
                // only the letters remain, and they glow escape-green instead of the paint colour.
                Color green = new Color(0.22f, 0.95f, 0.36f, 1f);
                m.SetColor("_BaseColor", green);
                m.SetTexture("_EmissiveColorMap", null);
                m.SetColor("_EmissiveColorLDR", green);
                m.SetColor("_EmissiveColor", green.linear * BacklitNits);
                m.SetFloat("_EmissiveIntensity", BacklitNits);
                m.SetFloat("_UseEmissiveIntensity", 0f);
                m.SetFloat("_EmissiveExposureWeight", 1f);
            }
            else if (backlit)
            {
                m.SetTexture("_EmissiveColorMap", tex);
                m.SetColor("_EmissiveColorLDR", Color.white);
                m.SetColor("_EmissiveColor", Color.white * BacklitNits);
                m.SetFloat("_EmissiveIntensity", BacklitNits);
                m.SetFloat("_UseEmissiveIntensity", 1f);
                m.SetFloat("_EmissiveExposureWeight", 1f);
            }
            else
            {
                m.SetTexture("_EmissiveColorMap", null);
                m.SetColor("_EmissiveColor", Color.black);
                m.SetFloat("_EmissiveIntensity", 0f);
            }
            HDMaterial.ValidateMaterial(m);
            EditorUtility.SetDirty(m);
            s_cache[name] = m;
            return m;
        }

        /// <summary>Light box artwork: trilinear + anisotropic mips, clamped, no alpha (sharp letters at a distance).</summary>
        private static void ConfigureLightboxImport(Texture2D tex)
        {
            var ti = AssetImporter.GetAtPath(AssetDatabase.GetAssetPath(tex)) as TextureImporter;
            if (ti == null) return;
            if (ti.mipmapEnabled && ti.anisoLevel == 8 && ti.wrapMode == TextureWrapMode.Clamp && ti.alphaSource == TextureImporterAlphaSource.None
                && ti.maxTextureSize >= 2048 && ti.npotScale == TextureImporterNPOTScale.None) return;
            ti.textureType = TextureImporterType.Default;
            ti.sRGBTexture = true;
            ti.mipmapEnabled = true;
            ti.mipmapFilter = TextureImporterMipFilter.KaiserFilter;
            ti.filterMode = FilterMode.Trilinear;
            ti.anisoLevel = 8;
            ti.wrapMode = TextureWrapMode.Clamp;
            ti.alphaSource = TextureImporterAlphaSource.None;
            ti.npotScale = TextureImporterNPOTScale.None;
            ti.maxTextureSize = 2048;
            ti.textureCompression = TextureImporterCompression.CompressedHQ;
            ti.SaveAndReimport();
        }

        /// <summary>Dark painted backing plate of every sign (the palette's DarkPaintedMetal, no palette needed).</summary>
        public static Material PlateMaterial()
        {
            const string key = "__plate";
            if (s_cache.TryGetValue(key, out Material cached) && cached != null) return cached;
            Material m = AssetDatabase.LoadAssetAtPath<Material>("Assets/Art/Materials/World/MAT_DarkPaintedMetal.mat");
            s_cache[key] = m;
            return m;
        }

        /// <summary>Material for a world-space TextMeshPro label (texts with no artwork): the TMP font atlas on the HDRP
        /// lit SDF shader, white letters.</summary>
        public static Material LabelMaterial(TMPro.TMP_FontAsset font)
        {
            const string name = "MAT_SignLabel_HDRP";
            if (s_cache.TryGetValue(name, out Material cached) && cached != null) return cached;
            Shader sh = Shader.Find("TextMeshPro/SRP/TMP_SDF-HDRP LIT");
            if (font == null || sh == null) return null;
            EnsureFolder(SignMaterialFolder);
            string path = $"{SignMaterialFolder}/{name}.mat";
            Material m = AssetDatabase.LoadAssetAtPath<Material>(path);
            if (m == null)
            {
                m = new Material(font.material) { name = name };
                AssetDatabase.CreateAsset(m, path);
            }
            m.shader = sh;
            m.SetTexture("_MainTex", font.atlasTexture);
            if (m.HasProperty("_FaceColor")) m.SetColor("_FaceColor", new Color(0.92f, 0.92f, 0.88f, 1f));
            EditorUtility.SetDirty(m);
            s_cache[name] = m;
            return m;
        }

        /// <summary>"Sign_ToCorridor" -> "TO CORRIDOR"; used when a sign has neither text nor artwork.</summary>
        public static string TextFromName(string objectName)
        {
            string s = Regex.Replace(objectName ?? "", @"^(Menu)?Sign_?", "");
            s = Regex.Replace(s, @"(?<=[a-z])(?=[A-Z])|_", " ");
            return s.Trim().ToUpperInvariant();
        }

        public static void EnsureFolder(string folder)
        {
            if (AssetDatabase.IsValidFolder(folder)) return;
            string parent = System.IO.Path.GetDirectoryName(folder).Replace('\\', '/');
            EnsureFolder(parent);
            AssetDatabase.CreateFolder(parent, System.IO.Path.GetFileName(folder));
        }

        // ------------------------------------------------------------------------------------------------------------
        // POST-BUILD: put every face on the visible surface
        // ------------------------------------------------------------------------------------------------------------

        /// <summary>
        /// Signs are authored at a door's centre line (inside the lintel) or a few centimetres in front of a wall.
        /// Embedded signs get each face moved onto the wall surface on its side; faces of free signs that look
        /// straight into a wall (closer than FreeSignWallGap) are removed and the rest of the sign moves onto that wall.
        /// </summary>
        public static string Apply()
        {
            Physics.SyncTransforms();
            int signs = 0, snapped = 0, culled = 0, wallSnapped = 0;
            int envMask = ~((1 << 13) | (1 << 12) | (1 << 9) | (1 << 2));
            var roots = new List<Transform>();
            foreach (Transform t in UnityEngine.Object.FindObjectsByType<Transform>(FindObjectsInactive.Exclude))
            {
                if (t.Find(FaceFront) != null || t.Find(FaceBack) != null) roots.Add(t);
            }

            foreach (Transform root in roots)
            {
                signs++;
                Vector3 c = root.position;
                Vector3 f = root.forward;
                bool embedded = false;
                foreach (Collider col in Physics.OverlapBox(c, new Vector3(0.05f, 0.05f, 0.01f), root.rotation, envMask, QueryTriggerInteraction.Ignore))
                {
                    if (col != null && !col.transform.IsChildOf(root)) { embedded = true; break; }
                }

                Vector3 snapToWall = Vector3.zero;
                foreach (string faceName in new[] { FaceFront, FaceBack })
                {
                    Transform face = root.Find(faceName);
                    if (face == null) continue;
                    Transform plate = root.Find(faceName.Replace("SignFace", "SignPlate"));
                    Transform label = root.Find(faceName.Replace("SignFace", "SignLabel"));
                    // a quad is seen from its -Z side; the face's outward normal is -face.forward
                    Vector3 n = -face.forward;
                    if (embedded)
                    {
                        if (Physics.Raycast(c + n * 1.5f, -n, out RaycastHit hit, 1.5f, envMask, QueryTriggerInteraction.Ignore))
                        {
                            float d = Vector3.Dot(hit.point - c, n);
                            Shift(root, face, plate, label, n, d);
                            snapped++;
                        }
                    }
                    else if (Physics.Raycast(c, n, out RaycastHit wallHit, FreeSignWallGap, envMask, QueryTriggerInteraction.Ignore))
                    {
                        // the other face hangs in front of this wall: move it back onto the wall (no floating gap)
                        snapToWall = n * Mathf.Max(0f, wallHit.distance - 0.005f);
                        RemoveFromMember(root, face);
                        UnityEngine.Object.DestroyImmediate(face.gameObject);
                        if (plate != null) UnityEngine.Object.DestroyImmediate(plate.gameObject);
                        if (label != null) UnityEngine.Object.DestroyImmediate(label.gameObject);
                        culled++;
                    }
                }
                if (snapToWall.sqrMagnitude > 1e-6f)
                {
                    foreach (Transform child in root) child.position += snapToWall;
                    wallSnapped++;
                }
            }
            return $"signs={signs} faces snapped to walls={snapped} faces culled={culled} free signs moved onto their wall={wallSnapped}";
        }

        private static void Shift(Transform root, Transform face, Transform plate, Transform label, Vector3 n, float surfaceDistance)
        {
            // plate (2 cm thick) on the wall, face 3 mm in front of the plate
            float plateD = surfaceDistance + 0.011f;
            float faceD = surfaceDistance + 0.025f;
            Vector3 c = root.position;
            face.position = c + n * faceD + Vector3.ProjectOnPlane(face.position - c, n);
            if (plate != null) plate.position = c + n * plateD + Vector3.ProjectOnPlane(plate.position - c, n);
            if (label != null) label.position = c + n * (faceD + 0.002f) + Vector3.ProjectOnPlane(label.position - c, n);
        }

        private static void RemoveFromMember(Transform root, Transform face)
        {
            var member = root.GetComponent<Cretacea.Core.LightGroupMember>();
            Renderer r = face.GetComponent<Renderer>();
            if (member == null || r == null) return;
            var so = new SerializedObject(member);
            SerializedProperty ep = so.FindProperty("emissiveRenderers");
            for (int i = ep.arraySize - 1; i >= 0; i--)
            {
                var o = ep.GetArrayElementAtIndex(i).objectReferenceValue;
                if (o == null || o == r) { ep.GetArrayElementAtIndex(i).objectReferenceValue = null; ep.DeleteArrayElementAtIndex(i); }
            }
            so.ApplyModifiedPropertiesWithoutUndo();
        }
    }
